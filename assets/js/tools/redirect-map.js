/* AEM redirect map builder: paste old and new URLs, get validated, flattened Apache,
   _redirects and Edge Delivery Services rules. Runs in the browser; nothing is uploaded. */
(function (root) {
  'use strict';

  var HEADER = /^(source|old|from|url|legacy|origin)/i;
  function splitLine(line) {
    var m = line.split(/\t|,|\s*->\s*|\s*=>\s*|\s+/).map(function (s) { return s.trim().replace(/^["']|["']$/g, ''); }).filter(Boolean);
    return m;
  }
  function pathOf(u) {
    if (/^https?:\/\//i.test(u)) { try { var x = new URL(u); return x.pathname + x.search; } catch (e) { return null; } }
    return u.charAt(0) === '/' ? u : '/' + u;
  }
  // identity of a source for loop and duplicate checks
  function keyOf(p) { return p.split('?')[0].replace(/\.html$/i, '').replace(/\/+$/, '').toLowerCase() || '/'; }

  function parse(text, opts) {
    var rows = [], issues = [];
    String(text || '').split(/\r\n|\r|\n/).forEach(function (raw, i) {
      var line = raw.trim();
      if (!line || line.charAt(0) === '#') return;
      var c = splitLine(line);
      if (i === 0 && HEADER.test(c[0] || '') && !/^\//.test(c[0])) return;
      if (c.length < 2) { issues.push({ level: 'error', text: 'Line ' + (i + 1) + ' needs a source and a destination.', detail: raw.trim().slice(0, 80) }); return; }
      var src = pathOf(c[0]);
      if (!src) { issues.push({ level: 'error', text: 'Line ' + (i + 1) + ': the source isn\'t a valid URL.', detail: c[0] }); return; }
      var status = /^30[12378]$/.test(c[2] || '') ? c[2] : String((opts && opts.status) || 301);
      rows.push({ line: i + 1, src: src, dest: c[1], status: status, key: keyOf(src) });
    });
    return { rows: rows, issues: issues };
  }

  function analyse(rows, opts) {
    var issues = [], byKey = {}, out = [];
    rows.forEach(function (r) {
      if (byKey[r.key]) { issues.push({ level: 'error', text: 'Duplicate source: ' + r.src, detail: 'Lines ' + byKey[r.key].line + ' and ' + r.line + '. The first one is kept.' }); return; }
      byKey[r.key] = r; out.push(r);
    });
    out.forEach(function (r) {
      var destPath = /^https?:\/\//i.test(r.dest) ? null : pathOf(r.dest);
      r.destKey = destPath ? keyOf(destPath) : null;
      if (r.destKey === r.key) { r.bad = true; issues.push({ level: 'error', text: 'Redirects to itself: ' + r.src, detail: 'Line ' + r.line + '. Removed.' }); }
      if (r.src.indexOf('?') > -1) issues.push({ level: 'warn', text: 'Source has a query string: ' + r.src, detail: 'Rules match the path only, so the Apache output adds a RewriteCond for the query.' });
      if (!destPath && !/^https?:\/\/[^/]+/i.test(r.dest)) issues.push({ level: 'error', text: 'Destination looks invalid: ' + r.dest, detail: 'Line ' + r.line });
    });
    out = out.filter(function (r) { return !r.bad; });
    var index = {}; out.forEach(function (r) { index[r.key] = r; });
    var chains = 0, loops = 0;
    out.forEach(function (r) {
      var seen = {}, cur = r, hops = 0;
      seen[r.key] = 1;
      while (cur.destKey && index[cur.destKey]) {
        cur = index[cur.destKey]; hops++;
        if (seen[cur.key]) { r.loop = true; break; }
        seen[cur.key] = 1;
      }
      if (r.loop) { loops++; issues.push({ level: 'error', text: 'Redirect loop starting at ' + r.src, detail: 'Line ' + r.line + '. It is removed from the output; fix the cycle.' }); return; }
      r.final = hops ? cur.dest : r.dest; r.hops = hops;
      if (hops) { chains++; issues.push({ level: 'warn', text: 'Chain of ' + (hops + 1) + ' redirects: ' + r.src + ' → … → ' + r.final, detail: (opts && opts.flatten) ? 'Flattened to one hop.' : 'Turn on "Flatten chains" so visitors and crawlers make one hop.' }); }
    });
    out = out.filter(function (r) { return !r.loop; });
    out.forEach(function (r) { r.to = (opts && opts.flatten) ? r.final : r.dest; });
    return { rows: out, issues: issues, chains: chains, loops: loops };
  }

  function reEscape(s) { return s.replace(/[.+?^${}()|[\]\\*]/g, '\\$&'); }
  function apache(rows, o) {
    var lines = ['# Generated by the AEM redirect map builder'];
    rows.forEach(function (r) {
      var parts = r.src.split('?'), p = parts[0].replace(/\/+$/, '') || '/';
      var tail = o.html ? '(\\.html)?' : '';
      var pattern = p === '/' ? '^/$' : '^' + reEscape(p.replace(/\.html$/i, '')) + tail + '/?$';
      if (parts[1]) lines.push('RewriteCond %{QUERY_STRING} ^' + reEscape(parts.slice(1).join('?')) + '$');
      lines.push('RewriteRule ' + pattern + ' ' + r.to + ' [R=' + r.status + ',L,NE' + (o.nocase ? ',NC' : '') + ']');
    });
    return lines.join('\n');
  }
  function netlify(rows) { return rows.map(function (r) { return r.src.split('?')[0].replace(/\.html$/i, '') + ' ' + r.to + ' ' + r.status; }).join('\n'); }
  function eds(rows) {
    return ['Source\tDestination'].concat(rows.filter(function (r) { return r.src.indexOf('?') < 0; }).map(function (r) { return r.src.split('?')[0].replace(/\.html$/i, '') + '\t' + r.to; })).join('\n');
  }
  function build(text, opts) {
    var p = parse(text, opts), a = analyse(p.rows, opts);
    return { total: p.rows.length, rows: a.rows, issues: p.issues.concat(a.issues), chains: a.chains, loops: a.loops,
      apache: apache(a.rows, opts), netlify: netlify(a.rows), eds: eds(a.rows) };
  }

  var api = { parse: parse, analyse: analyse, build: build, keyOf: keyOf };
  root.KJRedirects = api;
  if (typeof module !== 'undefined') module.exports = api;
  if (typeof document === 'undefined') return;

  function init() {
    var form = document.getElementById('rmForm'); if (!form) return;
    var out = document.getElementById('rmOut'), h = root.KJTools.h;
    var sample = 'Source,Destination,Status\n/en/about-us.html,/about/\n/about/,/company/\n/company/,/about-keval/\n/old/blog/post-1,/blog/post-1/\n/old/blog/post-1,/blog/post-one/\n/a,/b\n/b,/a\n/products?id=7,/shop/item-7/';
    document.getElementById('rmSample').addEventListener('click', function () { form.elements.rmText.value = sample; run(); });
    form.addEventListener('submit', function (e) { e.preventDefault(); run(); });
    function run() {
      var o = { flatten: form.elements.rmFlatten.checked, html: form.elements.rmHtml.checked, nocase: form.elements.rmCase.checked, status: form.elements.rmStatus.value };
      out.hidden = false; out.textContent = '';
      var r = build(form.elements.rmText.value, o);
      if (!r.total) { out.appendChild(h('p', { class: 'pc-error', role: 'alert', text: 'Paste at least one "old, new" pair.' })); return; }
      out.appendChild(h('div', { class: 'kt-tiles' }, KJA.stat('Pairs read', r.total), KJA.stat('Rules output', r.rows.length), KJA.stat('Chains', r.chains, r.chains ? 'mid' : ''), KJA.stat('Loops', r.loops, r.loops ? 'bad' : '')));
      if (r.issues.length) out.appendChild(h('div', null, h('h3', { text: 'Issues' }), KJA.findings(r.issues)));
      else out.appendChild(KJA.findings([{ level: 'ok', text: 'No duplicates, loops or chains found.' }]));
      if (!r.rows.length) return;
      out.appendChild(KJA.codeBlock('Apache rewrite rules', r.apache, 'redirects.rules', 'Add to your Dispatcher rewrite rules (conf.d/rewrites/rewrite.rules in the SDK layout), then test with the Dispatcher SDK.'));
      out.appendChild(KJA.codeBlock('Edge Delivery Services redirects sheet', r.eds, 'redirects.tsv', 'Paste into a sheet named redirects with the headers Source and Destination, then publish it.'));
      out.appendChild(KJA.codeBlock('_redirects (Netlify, Cloudflare Pages)', r.netlify, '_redirects'));
    }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
})(typeof window !== 'undefined' ? window : globalThis);
